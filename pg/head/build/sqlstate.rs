use std::fs;
use std::path::Path;

/// Generates `SqlState`: a variant per SQLSTATE condition PostgreSQL 18
/// itself defines, from its own `errcodes.txt` (vendored verbatim into
/// `capture/out/errcodes.txt`; see `capture/README.md` for provenance).
/// No code is hand-listed; every variant, its code and its PostgreSQL
/// condition name come from parsing that file.
///
/// The variant name is PascalCase of the condition name (`errcodes.txt`'s
/// fourth field, the PL/pgSQL condition name), because that is the name
/// callers already use (`SqlState::SyntaxError`, `SqlState::UndefinedTable`,
/// ...). A handful of conditions share one condition name across distinct
/// SQLSTATEs (for example `modifying_sql_data_not_permitted` is both a SQL
/// routine exception, `2F002`, and an external routine exception, `38002`);
/// every variant whose condition name is not unique across the file gets
/// its SQLSTATE code appended, so the rename is total and mechanical, not
/// a hand-picked exception per collision.
///
/// One further exception, requested explicitly: `XX000`'s condition name
/// is `internal_error`, whose PascalCase would be `InternalError`, but the
/// head already spells this variant `SqlState::Internal` at every one of
/// its many raise sites (it is not a PostgreSQL-authored message, it is an
/// invariant violation: `HeadError::internal`). That single rename is the
/// only hand-listed name in this generator.
pub(crate) fn generate(errcodes_path: &Path) -> Result<String, String> {
    crate::record_read(errcodes_path);
    let text = fs::read_to_string(errcodes_path)
        .map_err(|error| format!("reading {}: {error}", errcodes_path.display()))?;

    let mut conditions = Vec::new();
    for line in text.lines() {
        let line = line.trim_end();
        if line.is_empty() || line.starts_with('#') || line.starts_with("Section:") {
            continue;
        }
        let fields: Vec<&str> = line.split_ascii_whitespace().collect();
        // Lines with only three fields are an alternate C macro name for a
        // code already carrying its condition name on another line (no
        // PL/pgSQL condition or SGML entry is generated for them either,
        // per errcodes.txt's own format comment); they name no condition of
        // their own, so they contribute no variant.
        let [code, _class, _macro_name, condition_name] = fields.as_slice() else {
            continue;
        };
        conditions.push(((*code).to_string(), (*condition_name).to_string()));
    }

    let mut name_counts = std::collections::HashMap::new();
    for (_, condition_name) in &conditions {
        *name_counts.entry(condition_name.clone()).or_insert(0u32) += 1;
    }

    let variants: Vec<(String, String)> = conditions
        .iter()
        .map(|(code, condition_name)| {
            let variant = if condition_name == "internal_error" {
                "Internal".to_string()
            } else if name_counts.get(condition_name).copied().unwrap_or(0) > 1 {
                format!("{}{}", pascal_case(condition_name), code)
            } else {
                pascal_case(condition_name)
            };
            (variant, code.clone())
        })
        .collect();

    let mut out = String::new();
    out.push_str(
        "/// Generated by `build/sqlstate.rs` from PostgreSQL 18's own `errcodes.txt`\n\
         /// (`capture/out/errcodes.txt`). Do not hand-edit; add codes by updating that\n\
         /// file from a matching PostgreSQL 18 install.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub enum SqlState {\n",
    );
    for (variant, _) in &variants {
        out.push_str(&format!("    {variant},\n"));
    }
    out.push_str(
        "}\n\nimpl SqlState {\n    pub fn code(self) -> &'static str {\n        match self {\n",
    );
    for (variant, code) in &variants {
        out.push_str(&format!("            SqlState::{variant} => \"{code}\",\n"));
    }
    out.push_str("        }\n    }\n}\n");
    Ok(out)
}

/// `SCREAMING_SNAKE_CASE` (`errcodes.txt`'s condition names are lowercase
/// `snake_case`, but this is written to also cope with an all-uppercase
/// macro suffix, since both only ever separate words with `_`) to
/// `PascalCase`.
fn pascal_case(snake: &str) -> String {
    snake
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) => {
                    first.to_ascii_uppercase().to_string() + &chars.as_str().to_ascii_lowercase()
                }
                None => String::new(),
            }
        })
        .collect()
}
